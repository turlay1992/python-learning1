# 'r' — читання тексту (файл має існувати), 
# 'w' — запис (створює або повністю затирає існуючий файл), 
# 'a' — дозапис у кінець, 
# 'x' — створити новий файл і впасти з помилкою, 
#       якщо він вже є (корисно, коли перезапис — 
#       це помилка користувача, а не нормальний сценарій), 
# 'r+' — читання й запис одночасно. 
# 'b' до будь-якого з них ('rb', 'wb') — і працюєш не з рядками, а з bytes.

